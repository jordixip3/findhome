def feed_open_portal_properties(db) -> int:
    """
    Feeds open portal real estate properties into the current database (MySQL or SQLite).
    Preserves existing communities, inserting or updating listings cleanly.
    """
    from datetime import datetime, timezone
    now = datetime.now(timezone.utc).isoformat()
    inserted_count = 0

    for prop in OPEN_PORTAL_PROPERTIES:
        rent_per_person = round(prop["total_rent"] / prop["ideal_roommates"], 2)
        images_json = json.dumps(prop["images"])

        # Check if property exists
        db.execute("SELECT id FROM properties WHERE id = ?", (prop["id"],))
        existing = db.fetchone()

        if existing:
            # Update property with updated metadata
            update_sql = """
            UPDATE properties SET
                title = ?, description = ?, city = ?, country = ?, address = ?,
                latitude = ?, longitude = ?, total_rent = ?, ideal_roommates = ?,
                rent_per_person = ?, bedrooms = ?, bathrooms = ?, surface_sqm = ?,
                property_type = ?, has_elevator = ?, is_exterior = ?, is_furnished = ?,
                has_terrace = ?, has_air_con = ?, energy_rating = ?, source_portal = ?,
                source_url = ?, images = ?, contact_name = ?, contact_phone = ?,
                contact_email = ?, contact_whatsapp = ?, status = 'available'
            WHERE id = ?
            """
            params = (
                prop["title"], prop["description"], prop["city"], prop["country"], prop["address"],
                prop["latitude"], prop["longitude"], prop["total_rent"], prop["ideal_roommates"],
                rent_per_person, prop["bedrooms"], prop["bathrooms"], prop["surface_sqm"],
                prop["property_type"], prop["has_elevator"], prop["is_exterior"], prop["is_furnished"],
                prop["has_terrace"], prop["has_air_con"], prop["energy_rating"], prop["source_portal"],
                prop["source_url"], images_json, prop["contact_name"], prop["contact_phone"],
                prop["contact_email"], prop["contact_whatsapp"], prop["id"]
            )
            db.execute(update_sql, params)
        else:
            insert_sql = """
            INSERT INTO properties (
                id, title, description, city, country, address, latitude, longitude,
                total_rent, ideal_roommates, rent_per_person, bedrooms, bathrooms,
                surface_sqm, property_type, has_elevator, is_exterior, is_furnished,
                has_terrace, has_air_con, energy_rating, source_portal, source_url,
                images, contact_name, contact_phone, contact_email, contact_whatsapp,
                status, created_at
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 'available', ?)
            """
            params = (
                prop["id"], prop["title"], prop["description"], prop["city"], prop["country"], prop["address"],
                prop["latitude"], prop["longitude"], prop["total_rent"], prop["ideal_roommates"],
                rent_per_person, prop["bedrooms"], prop["bathrooms"], prop["surface_sqm"],
                prop["property_type"], prop["has_elevator"], prop["is_exterior"], prop["is_furnished"],
                prop["has_terrace"], prop["has_air_con"], prop["energy_rating"], prop["source_portal"],
                prop["source_url"], images_json, prop["contact_name"], prop["contact_phone"],
                prop["contact_email"], prop["contact_whatsapp"], now
            )
            db.execute(insert_sql, params)
            inserted_count += 1

    return len(OPEN_PORTAL_PROPERTIES)
